let lang = 'de';
export const getLang = () => lang;
export function setLang(l) { lang = STRINGS[l] ? l : 'de'; }

export function t(key, vars, l = lang) {
  let s = STRINGS[l][key] ?? STRINGS.de[key] ?? key;
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}
